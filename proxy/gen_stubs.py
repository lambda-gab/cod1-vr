# Generates forwarding stubs + .def for every export of the 32-bit system opengl32.dll.
# Functions listed in HOOKED are implemented by hand in cod_vr.c.
import sys
names=[l.strip() for l in open(sys.argv[1]) if l.strip()]
HOOKED={'glDrawBuffer','glReadBuffer','wglMakeCurrent'}
c=['// generated by gen_stubs.py - do not edit','#include <windows.h>',
   'FARPROC g_real[%d];'%len(names),'const char *g_realNames[%d] = {'%len(names)]
c+=['  "%s",'%n for n in names]+['};','const int g_realCount = %d;'%len(names)]
d=['LIBRARY opengl32','EXPORTS']
for i,n in enumerate(names):
    if n in HOOKED:
        d.append('  %s=hook_%s'%(n,n)); continue
    c.append('__declspec(naked) void stub_%d(void) { __asm jmp dword ptr [g_real + %d] }'%(i,4*i))
    d.append('  %s=stub_%d'%(n,i))
open(sys.argv[2],'w').write('\n'.join(c)+'\n')
open(sys.argv[3],'w').write('\n'.join(d)+'\n')
print(len(names),'exports')
